#!/usr/bin/env python3
"""
Build a combined ROM with assets + baked chunk data + CI8 tiles embedded.

Layout:
  0x000000 - 0x000FFF   Header + IPL3 (from trx-n64.z64)
  0x001000 - 0x0FFFFF   Game code (padded to 1 MB)
  0x100000 - ???         Asset archive (tr1_assets.bin)
  BAKE_OFFSET - ???      Baked chunk data (level1.baked, optional)
  CI8_OFFSET  - end      CI8 texture tiles (level1.ci8tiles, optional)

The game reads assets via PI DMA from ROM offset 0x100000.
Baked data and CI8 tile offsets are stored in baked_offsets.h.
"""

import sys
import os

def build_full_rom(rom_path, assets_path, output_path, baked_path=None, ci8_path=None):
    with open(rom_path, "rb") as f:
        rom = f.read()

    with open(assets_path, "rb") as f:
        assets = f.read()

    # Pad ROM to exactly 1 MB (0x100000)
    ASSET_OFFSET = 0x100000
    if len(rom) < ASSET_OFFSET:
        rom = rom + b'\x00' * (ASSET_OFFSET - len(rom))
    elif len(rom) > ASSET_OFFSET:
        print(f"WARNING: ROM is {len(rom)} bytes, larger than {ASSET_OFFSET}!")

    # Combine code + assets
    full = bytearray(rom[:ASSET_OFFSET]) + bytearray(assets)

    # Pad to 4-byte alignment
    while len(full) % 4:
        full += b'\x00'

    # Append baked chunk data if available
    bake_offset = 0
    bake_size = 0
    if baked_path and os.path.exists(baked_path):
        # Align to 16 bytes for DMA
        while len(full) % 16:
            full += b'\x00'
        bake_offset = len(full)
        with open(baked_path, "rb") as f:
            baked = f.read()
        full += bytearray(baked)
        bake_size = len(baked)
        # Pad to 4-byte alignment
        while len(full) % 4:
            full += b'\x00'

    # Append CI8 texture tiles if available
    ci8_offset = 0
    ci8_size = 0
    if ci8_path and os.path.exists(ci8_path):
        # Align to 16 bytes for DMA
        while len(full) % 16:
            full += b'\x00'
        ci8_offset = len(full)
        with open(ci8_path, "rb") as f:
            ci8 = f.read()
        full += bytearray(ci8)
        ci8_size = len(ci8)
        while len(full) % 4:
            full += b'\x00'

    with open(output_path, "wb") as f:
        f.write(full)

    print(f"Combined ROM: {output_path}")
    print(f"  Code:   {ASSET_OFFSET/1024:.0f} KB (padded)")
    print(f"  Assets: {len(assets)/1024/1024:.1f} MB at offset 0x{ASSET_OFFSET:X}")
    if bake_offset:
        print(f"  Baked:  {bake_size/1024:.1f} KB at offset 0x{bake_offset:X}")
    if ci8_offset:
        print(f"  CI8:    {ci8_size/1024:.1f} KB at offset 0x{ci8_offset:X}")
    print(f"  Total:  {len(full)/1024/1024:.1f} MB")

    # Write header file with offsets for C code
    header_path = os.path.join(os.path.dirname(output_path), "baked_offsets.h")
    with open(header_path, "w") as f:
        f.write(f"/* Auto-generated by build_full_rom.py */\n")
        f.write(f"#define BAKED_ROM_OFFSET  0x{bake_offset:X}u\n")
        f.write(f"#define BAKED_ROM_SIZE    {bake_size}u\n")
        f.write(f"#define CI8_ROM_OFFSET    0x{ci8_offset:X}u\n")
        f.write(f"#define CI8_ROM_SIZE      {ci8_size}u\n")
    print(f"  Header: {header_path}")

if __name__ == "__main__":
    if len(sys.argv) < 4:
        print(f"Usage: {sys.argv[0]} <rom.z64> <assets.bin> <output.z64> [baked.baked] [ci8.ci8tiles]")
        sys.exit(1)
    baked = sys.argv[4] if len(sys.argv) > 4 else None
    ci8 = sys.argv[5] if len(sys.argv) > 5 else None
    build_full_rom(sys.argv[1], sys.argv[2], sys.argv[3], baked, ci8)
