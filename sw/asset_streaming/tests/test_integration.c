/**
 * End-to-end integration test for the full asset streaming pipeline.
 *
 * Tests the COMPLETE path: pack archive (via Python) -> init manager ->
 * load assets -> verify decompressed data -> test eviction -> test pinning.
 *
 * Uses a file-backed SD backend so the entire pipeline runs on the host.
 *
 * Build and run:
 *   # First, generate the test archive:
 *   python3 gen_test_archive.py
 *
 *   # Then build and run:
 *   cc -DASSET_HOST_BUILD -DASSET_DEBUG -o test_integration \
 *      test_integration.c ../src/asset_manager.c ../src/asset_cache.c \
 *      ../src/lz4_decode.c ../src/asset_debug.c \
 *      -I../src -Wall -Wextra -Wno-unused-parameter && ./test_integration
 */

#ifndef ASSET_HOST_BUILD
#define ASSET_HOST_BUILD
#endif
#ifndef ASSET_DEBUG
#define ASSET_DEBUG
#endif

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdarg.h>
#include "asset_manager.h"
#include "asset_debug.h"

/* ---------- Test infrastructure ---------- */

static int tests_passed = 0;
static int tests_failed = 0;

#define TEST(name) \
    do { printf("  %-55s ", #name); } while(0)

#define PASS() \
    do { printf("[PASS]\n"); tests_passed++; } while(0)

#define FAIL(msg) \
    do { printf("[FAIL] %s\n", msg); tests_failed++; return; } while(0)

#define ASSERT(cond, msg) \
    do { if (!(cond)) { FAIL(msg); } } while(0)

/* Debug log handler */
static int debug_log(const char *fmt, ...) {
    /* Suppress debug output during tests. Uncomment to see: */
    /* va_list args; va_start(args, fmt); vprintf(fmt, args); va_end(args); */
    (void)fmt;
    return 0;
}

/* ---------- File-backed SD backend ---------- */

typedef struct {
    FILE *fp;
} file_sd_ctx_t;

static uint32_t file_sd_init(void *ctx) {
    file_sd_ctx_t *fctx = (file_sd_ctx_t *)ctx;
    return fctx->fp ? 0 : 1;
}

static uint32_t file_sd_deinit(void *ctx) {
    (void)ctx;
    return 0;
}

static uint32_t file_sd_read_sectors(void *ctx, void *dest,
                                      uint32_t sector, uint32_t count) {
    file_sd_ctx_t *fctx = (file_sd_ctx_t *)ctx;
    if (!fctx->fp) return 1;

    long offset = (long)sector * 512;
    if (fseek(fctx->fp, offset, SEEK_SET) != 0) return 1;

    size_t bytes = (size_t)count * 512;
    if (fread(dest, 1, bytes, fctx->fp) != bytes) return 1;

    return 0;
}

/* ---------- Test data definitions ---------- */

/*
 * The test archive is generated by gen_test_archive.py and contains:
 *   Asset 1: "ASSET_ONE_" repeated 100 times  (1000 bytes)
 *   Asset 2: "ASSET_TWO_" repeated 200 times  (2000 bytes)
 *   Asset 3: "ASSET_THREE_" repeated 300 times (3600 bytes)
 *   Asset 4: "FOUR" repeated 500 times         (2000 bytes)
 *   Asset 5: "FIVER" repeated 400 times        (2000 bytes)
 *
 * All compressed with LZ4.
 */

#define ARCHIVE_FILE    "test_archive.bin"
#define NUM_TEST_ASSETS 5

/* Regenerate expected data to compare against */
static void generate_expected(int asset_id, char *buf, int *size) {
    switch (asset_id) {
        case 1:
            for (int i = 0; i < 100; i++) memcpy(buf + i * 10, "ASSET_ONE_", 10);
            *size = 1000;
            break;
        case 2:
            for (int i = 0; i < 200; i++) memcpy(buf + i * 10, "ASSET_TWO_", 10);
            *size = 2000;
            break;
        case 3:
            for (int i = 0; i < 300; i++) memcpy(buf + i * 12, "ASSET_THREE_", 12);
            *size = 3600;
            break;
        case 4:
            for (int i = 0; i < 500; i++) memcpy(buf + i * 4, "FOUR", 4);
            *size = 2000;
            break;
        case 5:
            for (int i = 0; i < 400; i++) memcpy(buf + i * 5, "FIVER", 5);
            *size = 2000;
            break;
        default:
            *size = 0;
    }
}

/* ---------- Shared test state ---------- */

#define CACHE_SIZE      (4 * 4096)  /* 16 KB = 4 slots of 4 KB */
#define SLOT_SIZE       (4096)
#define STAGING_SIZE    (32768)     /* 32 KB staging */

static uint8_t fake_sdram[CACHE_SIZE];
static uint8_t staging[STAGING_SIZE];
static asset_manager_t mgr;
static file_sd_ctx_t sd_ctx;
static asset_sd_backend_t file_backend = {
    .init = file_sd_init,
    .deinit = file_sd_deinit,
    .read_sectors = file_sd_read_sectors,
    .ctx = &sd_ctx,
};

static int setup_manager(void) {
    sd_ctx.fp = fopen(ARCHIVE_FILE, "rb");
    if (!sd_ctx.fp) {
        printf("ERROR: Cannot open %s. Run gen_test_archive.py first.\n", ARCHIVE_FILE);
        return -1;
    }

    memset(fake_sdram, 0, sizeof(fake_sdram));
    memset(staging, 0, sizeof(staging));
    memset(&asset_debug, 0, sizeof(asset_debug));
    asset_debug_set_log(debug_log);

    asset_error_t err = asset_init(&mgr, &(asset_init_config_t){
        .archive_base_sector = 0,
        .cache_base = fake_sdram,
        .cache_size = CACHE_SIZE,
        .slot_size = SLOT_SIZE,
        .staging_buffer = staging,
        .staging_size = STAGING_SIZE,
        .backend = &file_backend,
    });

    if (err != ASSET_OK) {
        printf("ERROR: asset_init failed: %s\n", asset_error_string(err));
        fclose(sd_ctx.fp);
        return -1;
    }

    return 0;
}

static void teardown_manager(void) {
    asset_shutdown(&mgr);
    if (sd_ctx.fp) {
        fclose(sd_ctx.fp);
        sd_ctx.fp = NULL;
    }
}

/* ---------- Tests ---------- */

static void test_cold_load_and_verify(void) {
    TEST(cold_load_each_asset_and_verify_data);
    if (setup_manager()) { FAIL("setup failed"); }

    char expected[4096];
    int expected_size;

    for (int id = 1; id <= NUM_TEST_ASSETS; id++) {
        uint32_t loaded_size = 0;
        void *data = asset_load_with_size(&mgr, id, &loaded_size);
        if (!data) {
            printf("[FAIL] asset %d load failed: %s\n", id,
                   asset_error_string(mgr.last_error));
            tests_failed++;
            teardown_manager();
            return;
        }

        generate_expected(id, expected, &expected_size);
        if (loaded_size != (uint32_t)expected_size) {
            printf("[FAIL] asset %d size mismatch: got %u, expected %d\n",
                   id, loaded_size, expected_size);
            tests_failed++;
            teardown_manager();
            return;
        }
        if (memcmp(data, expected, expected_size) != 0) {
            printf("[FAIL] asset %d data mismatch\n", id);
            tests_failed++;
            teardown_manager();
            return;
        }
    }

    teardown_manager();
    PASS();
}

static void test_hot_load(void) {
    TEST(hot_load_returns_same_data_instantly);
    if (setup_manager()) { FAIL("setup failed"); }

    void *first = asset_load(&mgr, 1);
    ASSERT(first != NULL, "first load failed");

    uint32_t hits_before = mgr.cache.hit_count;
    void *second = asset_load(&mgr, 1);
    ASSERT(second != NULL, "second load failed");
    ASSERT(second == first, "pointer changed on hot load");
    ASSERT(mgr.cache.hit_count == hits_before + 1, "no cache hit recorded");

    teardown_manager();
    PASS();
}

static void test_prefetch_then_load(void) {
    TEST(prefetch_then_load_is_cache_hit);
    if (setup_manager()) { FAIL("setup failed"); }

    asset_error_t err = asset_prefetch(&mgr, 2);
    ASSERT(err == ASSET_OK, "prefetch failed");
    ASSERT(asset_is_cached(&mgr, 2), "not cached after prefetch");

    uint32_t hits_before = mgr.cache.hit_count;
    void *data = asset_load(&mgr, 2);
    ASSERT(data != NULL, "load after prefetch failed");
    /* The is_cached call above counts as a hit, so just check we got another */
    ASSERT(mgr.cache.hit_count > hits_before, "no hit on post-prefetch load");

    teardown_manager();
    PASS();
}

static void test_eviction_under_pressure(void) {
    TEST(eviction_works_with_more_assets_than_slots);
    if (setup_manager()) { FAIL("setup failed"); }

    /* We have 4 slots. Load all 5 assets - one must be evicted. */
    for (int id = 1; id <= NUM_TEST_ASSETS; id++) {
        void *data = asset_load(&mgr, id);
        ASSERT(data != NULL, "load failed during pressure test");
    }

    /* Verify the most recent 4 are cached, asset 1 should be evicted */
    ASSERT(!asset_is_cached(&mgr, 1), "asset 1 should have been evicted");
    ASSERT(asset_is_cached(&mgr, 2), "asset 2 should be cached");
    ASSERT(asset_is_cached(&mgr, 5), "asset 5 should be cached");

    /* Reload asset 1 - should work (cold load) */
    char expected[4096];
    int expected_size;
    uint32_t loaded_size;
    void *data = asset_load_with_size(&mgr, 1, &loaded_size);
    ASSERT(data != NULL, "reload of evicted asset failed");
    generate_expected(1, expected, &expected_size);
    ASSERT(loaded_size == (uint32_t)expected_size, "reloaded size wrong");
    ASSERT(memcmp(data, expected, expected_size) == 0, "reloaded data wrong");

    teardown_manager();
    PASS();
}

static void test_pin_survives_eviction(void) {
    TEST(pinned_asset_survives_full_eviction_cycle);
    if (setup_manager()) { FAIL("setup failed"); }

    /* Load and pin asset 1 */
    void *pinned = asset_load_pinned(&mgr, 1);
    ASSERT(pinned != NULL, "load_pinned failed");
    ASSERT(asset_is_pinned(&mgr, 1), "not pinned after load_pinned");

    /* Load 4 more assets to fill and overflow all slots */
    for (int id = 2; id <= NUM_TEST_ASSETS; id++) {
        asset_load(&mgr, id);
    }

    /* Asset 1 must still be there */
    ASSERT(asset_is_cached(&mgr, 1), "pinned asset was evicted!");
    void *still_there = asset_load(&mgr, 1);
    ASSERT(still_there == pinned, "pinned pointer changed");

    /* Verify data integrity */
    char expected[4096];
    int expected_size;
    generate_expected(1, expected, &expected_size);
    ASSERT(memcmp(pinned, expected, expected_size) == 0, "pinned data corrupted");

    asset_unpin(&mgr, 1);
    teardown_manager();
    PASS();
}

static void test_poison_after_eviction(void) {
    TEST(evicted_slot_memory_is_poisoned);
    if (setup_manager()) { FAIL("setup failed"); }

    /* Load asset 1 and remember its slot pointer */
    void *ptr1 = asset_load(&mgr, 1);
    ASSERT(ptr1 != NULL, "load failed");

    /* Fill remaining slots */
    for (int id = 2; id <= 4; id++) {
        asset_load(&mgr, id);
    }

    /* Load asset 5 - evicts asset 1 */
    asset_load(&mgr, 5);

    /* ptr1 now points to poisoned (then overwritten) memory.
     * Check that the eviction counter increased. */
    ASSERT(asset_debug.eviction_count >= 1, "no evictions recorded");

    teardown_manager();
    PASS();
}

static void test_leak_detection_on_shutdown(void) {
    TEST(shutdown_detects_leaked_pins);
    if (setup_manager()) { FAIL("setup failed"); }

    /* Load and pin, but don't unpin */
    asset_load_pinned(&mgr, 1);
    asset_load_pinned(&mgr, 2);

    /* Shutdown should report leaks via debug callback */
    /* (asset_shutdown calls asset_debug_check_leaks internally) */
    int leaks = asset_debug_check_leaks(&mgr);
    ASSERT(leaks == 2, "should detect 2 leaked pins");

    /* Clean up properly to avoid double-free */
    asset_unpin(&mgr, 1);
    asset_unpin(&mgr, 2);
    teardown_manager();
    PASS();
}

static void test_asset_not_found(void) {
    TEST(loading_nonexistent_asset_returns_null);
    if (setup_manager()) { FAIL("setup failed"); }

    void *data = asset_load(&mgr, 9999);
    ASSERT(data == NULL, "should return NULL");
    ASSERT(mgr.last_error == ASSET_ERR_NOT_FOUND, "wrong error code");

    teardown_manager();
    PASS();
}

static void test_flush_and_reload(void) {
    TEST(flush_then_reload_returns_correct_data);
    if (setup_manager()) { FAIL("setup failed"); }

    asset_load(&mgr, 1);
    asset_load(&mgr, 2);
    ASSERT(asset_is_cached(&mgr, 1), "asset 1 not cached");

    asset_flush(&mgr);
    ASSERT(!asset_is_cached(&mgr, 1), "asset 1 survived flush");

    /* Reload and verify */
    char expected[4096];
    int expected_size;
    uint32_t loaded_size;

    void *data = asset_load_with_size(&mgr, 1, &loaded_size);
    ASSERT(data != NULL, "reload after flush failed");
    generate_expected(1, expected, &expected_size);
    ASSERT(loaded_size == (uint32_t)expected_size, "size wrong after flush reload");
    ASSERT(memcmp(data, expected, expected_size) == 0, "data wrong after flush reload");

    teardown_manager();
    PASS();
}

/* ---------- Main ---------- */

int main(void) {
    printf("\n=== End-to-End Integration Tests ===\n\n");

    test_cold_load_and_verify();
    test_hot_load();
    test_prefetch_then_load();
    test_eviction_under_pressure();
    test_pin_survives_eviction();
    test_poison_after_eviction();
    test_leak_detection_on_shutdown();
    test_asset_not_found();
    test_flush_and_reload();

    printf("\n=== Results: %d passed, %d failed ===\n\n",
           tests_passed, tests_failed);

    return tests_failed > 0 ? 1 : 0;
}
